// Header, user strip, tab nav and sync status — the static chrome around the
// tab panels. Markup mirrors the vanilla index.html byte-for-byte where the
// e2e tests and styles.css depend on it.

import { useRef } from 'react';
import type { KeyboardEvent } from 'react';
import { supabase } from '../supabaseClient';
import { TABS, useApp } from '../context/AppContext';
import { roleLabel } from '../lib/format';

export function Header() {
  return (
    <header>
      <h1>Salärli</h1>
      <div className="sub">Lohnabrechnung für Angestellte im Privathaushalt · Vereinfachte Abrechnung Kanton Zürich · Stand 1.1.2026</div>
    </header>
  );
}

export function UserStrip() {
  const { ui, user, role } = useApp();
  return (
    <div id="user-strip" className="user-strip no-print" hidden={!ui.strip}>
      <span id="user-strip-name">{user?.email || ''}</span>
      <span id="user-strip-role" className={'role-badge' + (role ? ' ' + role : '')}>{role ? roleLabel(role) : ''}</span>
      <button type="button" id="btn-signout" onClick={() => { supabase.auth.signOut(); }}>Abmelden</button>
    </div>
  );
}

export function TabNav() {
  const { activeTab, tabVisible, showTab } = useApp();
  const navRef = useRef<HTMLElement>(null);

  // Hide the whole nav when only one tab is visible (e.g. an employee who
  // only ever sees Stundenerfassung) — a single-tab bar is just noise.
  const visibleCount = TABS.filter(t => tabVisible[t.id]).length;

  function onKeyDown(ev: KeyboardEvent<HTMLButtonElement>, idx: number) {
    const dir = ev.key === 'ArrowRight' || ev.key === 'End' ? 1
              : ev.key === 'ArrowLeft'  || ev.key === 'Home' ? -1
              : 0;
    if (!dir) return;
    ev.preventDefault();
    let next = ev.key === 'Home' ? 0
            : ev.key === 'End'  ? TABS.length - 1
            : (idx + dir + TABS.length) % TABS.length;
    let safety = TABS.length;
    while (!tabVisible[TABS[next].id] && safety-- > 0) {
      next = (next + dir + TABS.length) % TABS.length;
    }
    const target = TABS[next];
    if (!tabVisible[target.id]) return;
    showTab(target.id);
    navRef.current?.querySelector<HTMLButtonElement>(`#tab-${target.id}`)?.focus();
  }

  return (
    <nav role="tablist" aria-label="Bereiche" ref={navRef} hidden={visibleCount <= 1}>
      {TABS.map((t, idx) => {
        const active = activeTab === t.id;
        return (
          <button
            key={t.id}
            data-tab={t.id}
            id={`tab-${t.id}`}
            role="tab"
            aria-selected={active ? 'true' : 'false'}
            aria-controls={t.id}
            tabIndex={active ? 0 : -1}
            className={active ? 'active' : undefined}
            hidden={!tabVisible[t.id]}
            onClick={() => showTab(t.id)}
            onKeyDown={ev => onKeyDown(ev, idx)}
          >
            {t.label}
          </button>
        );
      })}
    </nav>
  );
}

export function SyncWarn() {
  const { sync } = useApp();
  return (
    <div id="sync-warn" className="danger no-print" hidden={!sync.warn} role="alert"
      style={{ margin: 0, borderRadius: 0, textAlign: 'center' }}>
      {sync.warn || ''}
    </div>
  );
}

export function SyncStatus() {
  const { sync } = useApp();
  const labels: Record<string, string> = { ok: 'Synchronisiert', pending: 'Speichern …', error: 'Fehler' };
  return (
    <div id="sync-status" className="sync-status no-print" data-state={sync.state} hidden={!sync.visible}>
      <span className="dot" aria-hidden="true"></span>
      <span id="sync-status-text">{labels[sync.state] || 'Bereit'}</span>
    </div>
  );
}

// Build version footer. config.js (generated by build.sh) sets
// window.__APP_VERSION; show "Entwicklungsversion" for local/unbuilt configs.
export function AppVersionFooter() {
  const v = window.__APP_VERSION;
  return (
    <footer id="app-version" className="app-version no-print">
      {(v && v.commit) ? `Version ${v.commit} · ${v.builtAt}` : 'Entwicklungsversion'}
    </footer>
  );
}
